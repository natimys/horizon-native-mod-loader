#!/usr/bin/env python3
"""Generate the static composition crate from a reviewed local source recipe."""
import argparse
import json
from pathlib import Path
import re
import tomllib

ROOT = Path(__file__).resolve().parents[1]
NAME = re.compile(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*\Z")
VERSION = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+\Z")


class PackError(ValueError):
    pass


def read_toml(path):
    return tomllib.loads(path.read_text(encoding="utf-8"))


def keys(value, allowed, required, label):
    if not isinstance(value, dict) or set(value) - allowed or required - set(value):
        raise PackError(f"{label}: expected {sorted(allowed)}, required {sorted(required)}")


def quote(value):
    return json.dumps(value, ensure_ascii=True)


def recipe(path, root=ROOT):
    root = root.resolve()
    data = read_toml(path)
    keys(data, {"schema", "api", "rust", "mods"}, {"schema", "api", "rust"}, "recipe")
    if type(data["schema"]) is not int or data["schema"] != 1:
        raise PackError("unsupported recipe schema; expected 1")
    api_source = (root / "native-mods/api/src/lib.rs").read_text()
    epoch = int(re.search(r"pub const API_VERSION: u32 = ([0-9]+);", api_source)[1])
    if type(data["api"]) is not int or data["api"] != epoch:
        raise PackError(f"unsupported API epoch; expected {epoch}")
    if not isinstance(data["rust"], str) or not VERSION.fullmatch(data["rust"]):
        raise PackError("rust must be an exact x.y.z version")
    mods = data.get("mods", [])
    if not isinstance(mods, list):
        raise PackError("mods must be an array of tables")
    packages, paths = set(), set()
    for mod in mods:
        keys(mod, {"package", "path", "version", "feature", "features"},
             {"package", "path", "version"}, "mod")
        package = mod["package"]
        if not isinstance(package, str) or not NAME.fullmatch(package):
            raise PackError("invalid Cargo package name")
        if package in packages:
            raise PackError(f"duplicate package: {package}")
        packages.add(package)
        value = mod["path"]
        if not isinstance(value, str) or not value.startswith("native-mods/mods/"):
            raise PackError("mod path must be inside native-mods/mods/")
        relative = Path(value)
        resolved = (root / relative).resolve()
        if relative.is_absolute() or ".." in relative.parts or not resolved.is_relative_to(root / "native-mods/mods"):
            raise PackError("mod path escapes the source workspace")
        if any((root / Path(*relative.parts[:i])).is_symlink() for i in range(1, len(relative.parts) + 1)):
            raise PackError("symlink mod paths are unsupported")
        if resolved in paths:
            raise PackError("duplicate mod path")
        paths.add(resolved)
        meta = read_toml(resolved / "Cargo.toml")["package"]
        if meta.get("name") != package or meta.get("version") != mod["version"]:
            raise PackError(f"{package}: package/version differs from Cargo.toml")
        if not isinstance(mod["version"], str) or not VERSION.fullmatch(mod["version"]):
            raise PackError("mod version must be exact x.y.z")
        if "feature" in mod and (not isinstance(mod["feature"], str) or not NAME.fullmatch(mod["feature"])):
            raise PackError("invalid optional pack feature")
        if mod.get("feature") == "default":
            raise PackError("default is reserved; omit feature for an always-linked mod")
        features = mod.get("features", [])
        if not isinstance(features, list) or any(not isinstance(f, str) or not NAME.fullmatch(f) for f in features):
            raise PackError("features must be Cargo feature names")
        if len(features) != len(set(features)):
            raise PackError("duplicate mod feature")
    data["mods"] = sorted(mods, key=lambda m: m["package"])
    return data


def generated(data, root=ROOT):
    runtime_version = read_toml(root / "native-mods/runtime/Cargo.toml")["package"]["version"]
    api_version = read_toml(root / "native-mods/api/Cargo.toml")["package"]["version"]
    cargo = ['# Generated by tools/native_modpack.py; edit native-modpack.toml.',
             '[package]', 'name = "horizon-native-pack"', 'version = "0.1.0"',
             'edition = "2021"', 'publish = false', '', '[dependencies]',
             f'horizon-native-runtime = {{ path = "../runtime", version = "={runtime_version}" }}']
    entries, features = [], {}
    for mod in sorted(data["mods"], key=lambda m: m["package"]):
        relative = Path("..") / Path(mod["path"]).relative_to("native-mods")
        fields = [f'path = {quote(relative.as_posix())}', f'version = "={mod["version"]}"', 'default-features = false']
        if mod.get("features"):
            fields.append('features = [' + ', '.join(quote(f) for f in sorted(mod["features"])) + ']')
        if "feature" in mod:
            fields.append('optional = true')
            features.setdefault(mod["feature"], []).append("dep:" + mod["package"])
            entries.append(f'            #[cfg(feature = {quote(mod["feature"])})]')
        cargo.append(f'{mod["package"]} = {{ ' + ', '.join(fields) + ' }')
        entries.append(f'            {mod["package"].replace("-", "_")}::create(),')
    cargo += ['', '[features]']
    for name, values in sorted(features.items()):
        cargo.append(f'{name} = [' + ', '.join(quote(v) for v in values) + ']')
    cargo += ['', '[dev-dependencies]', f'horizon-native-api = {{ path = "../api", version = "={api_version}" }}', '']
    source = '''//! Generated static composition. Edit native-modpack.toml, then regenerate.
use horizon_native_runtime::{HostSide, LoaderError, Runtime};

pub fn create_runtime() -> Result<Runtime, LoaderError> {
    create_for_side(HostSide::Combined)
}

/// The engine selects a host role; only this crate names concrete mods.
pub fn create_for_side(side: HostSide) -> Result<Runtime, LoaderError> {
    Runtime::for_side(
        vec![
''' + '\n'.join(entries) + '''
        ],
        side,
    )
}
'''
    # rustfmt keeps an empty vector compact; zero-mod packs are a supported recipe.
    if not entries:
        source = source[:source.index('    Runtime::for_side(')] + '    Runtime::for_side(vec![], side)\n}\n'
    return {"native-mods/pack/Cargo.toml": '\n'.join(cargo).encode(),
            "native-mods/pack/src/lib.rs": source.encode()}


def generate(path, check=False, root=ROOT):
    files = generated(recipe(path, root), root)
    mismatches = [name for name, value in files.items() if not (root / name).exists() or (root / name).read_bytes() != value]
    if check and mismatches:
        raise PackError("stale generated pack: " + ', '.join(mismatches))
    if not check:
        for name, value in files.items():
            (root / name).write_bytes(value)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__, epilog="Trusted native code runs with full process privileges. Review source before building.")
    parser.add_argument("--manifest", type=Path, default=ROOT / "native-modpack.toml")
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("generate", help="regenerate the existing composition crate")
    commands.add_parser("check", help="refuse stale generated files without writing")
    args = parser.parse_args()
    try:
        generate(args.manifest, args.command == "check")
    except (PackError, OSError, KeyError, tomllib.TOMLDecodeError) as error:
        parser.exit(1, f"native-modpack: {error}\n")
    print(f"native-modpack: {args.command} PASS")


if __name__ == "__main__":
    main()
